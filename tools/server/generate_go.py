"""Regenerate the pinned Go protocol; optionally reject checked-in drift."""
import argparse
import filecmp
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def schema_source():
    source = "// Code generated by tools/server/generate_go.py; DO NOT EDIT.\npackage main\n\n"
    for name in ("result", "error"):
        schema = (ROOT / "contracts/schemas" / (name + ".schema.json")).read_text(encoding="utf-8")
        source += "const " + name + "SchemaJSON = " + json.dumps(schema, ensure_ascii=True) + "\n"
    return source


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tools", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lock = json.loads(Path(__file__).with_name("toolchain-lock.json").read_text())
    tools = args.tools.resolve()
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=False)
    suffix = ".exe" if os.name == "nt" else ""
    plugins = {}
    for name, version in (("protoc-gen-go", lock["goProtobuf"]), ("protoc-gen-go-grpc", lock["goGrpcGenerator"])):
        path = tools / "go-bin" / (name + suffix)
        actual = subprocess.check_output([str(path), "--version"], encoding="utf-8").strip()
        if version.lstrip("v") != actual.split()[-1].lstrip("v"):
            raise RuntimeError("generator version mismatch")
        plugins[name] = path
    protoc = os.environ["PROTOC"]
    if subprocess.check_output([protoc, "--version"], encoding="utf-8").strip() != "libprotoc " + lock["protoc"]["version"]:
        raise RuntimeError("compiler version mismatch")
    command = [protoc, "--proto_path=" + str(ROOT / "contracts/grpc"), "--go_out=" + str(output), "--go_opt=paths=source_relative", "--go-grpc_out=" + str(output), "--go-grpc_opt=paths=source_relative"]
    command += ["--plugin=" + name + "=" + str(path) for name, path in plugins.items()]
    command += [str(ROOT / "contracts/grpc/knot/v1/configuration.proto")]
    subprocess.run(command, check=True)
    expected = ROOT / "examples/grpc/go/gen"
    files = sorted(path.relative_to(output) for path in output.rglob("*.go"))
    if args.check:
        if files != sorted(path.relative_to(expected) for path in expected.rglob("*.go")) or any(not filecmp.cmp(output / name, expected / name, shallow=False) for name in files):
            raise RuntimeError("generated Go drift")
    generated = output / "schemas_generated.go"
    generated.write_text(schema_source(), encoding="utf-8", newline="\n")
    subprocess.run(["gofmt", "-w", str(generated)], check=True)
    if args.check and generated.read_bytes() != (ROOT / "examples/grpc/go/schemas_generated.go").read_bytes():
        raise RuntimeError("generated Go schema drift")
    print(json.dumps({"generated": [p.as_posix() for p in files], "checked": args.check}))


if __name__ == "__main__":
    main()
